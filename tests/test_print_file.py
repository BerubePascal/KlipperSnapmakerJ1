# Tests of scripts/snapmaker_j1_print_file.py: python -m unittest discover tests
import importlib.util
import os
import tempfile
import unittest

SCRIPTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                       "scripts")
_spec = importlib.util.spec_from_file_location(
    "snapmaker_j1_print_file",
    os.path.join(SCRIPTS, "snapmaker_j1_print_file.py"))
pf = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pf)

# Purge line from X 0 to 137, then the model from X 100 to 140
FILE = b"""; generated by a slicer
; Extruder 0 Retraction Distance: 3
G28
G1 X0 Y5 F3000
G1 X137 Y5 E10
;LAYER_CHANGE
;Z:0.2
T0
G1 X100 Y100 F6000
G1 X140 Y100 E1.0
G1 X140 Y120 E1.0
G1 X120 Y120 E-0.8
; filament_retraction_length = 1.5,nil
; retraction_length = 0.8,0.8
"""


class PrintFileTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.gcodes = self.tmp.name
        self.chunk = pf.CHUNK

    def tearDown(self):
        pf.CHUNK = self.chunk
        self.tmp.cleanup()

    def write(self, data, name="part.gcode"):
        path = os.path.join(self.gcodes, name)
        with open(path, "wb") as f:
            f.write(data)
        return path

    def test_analyze_across_chunk_borders(self):
        path = self.write(FILE)
        for chunk in (5, 17, 64, 4 << 20):
            with self.subTest(chunk=chunk):
                pf.CHUNK = chunk
                info = pf.analyze(path)
                self.assertTrue(FILE[info["layer_pos"]:]
                                .startswith(b";LAYER_CHANGE"))
                self.assertEqual(info["range"], [0., 140.])
                self.assertEqual(info["model_range"], [100., 140.])
                self.assertEqual(info["tools"], {0})
                self.assertEqual(info["mode"], "FULL_CONTROL")
                # The filament profile wins, else the printer profile
                self.assertEqual(info["retraction"], [1.5, 0.8])

    def test_quick_check(self):
        info = pf.quick_check(self.write(FILE))
        self.assertEqual(info["retraction"], [1.5, 0.8])

    def test_mode_from_header_and_m605(self):
        luban = b";Extruder Mode: IDEX Mirror\n" + FILE
        self.assertEqual(pf.analyze(self.write(luban))["mode"], "MIRROR")
        orca = b"M605 S2\n" + FILE
        self.assertEqual(pf.analyze(self.write(orca))["mode"], "DUPLICATION")

    def test_modes_and_offsets(self):
        info = pf.analyze(self.write(FILE))
        for mode in pf.MODES:
            self.assertIsNone(pf.check_mode(info, mode))
        # Model center 120 to the center of the mode
        self.assertEqual(pf.x_offset(info, "DUPLICATION"), -40.)
        self.assertEqual(pf.x_offset(info, "MIRROR"), -45.)
        self.assertIsNone(pf.start_plan(info, "FULL_CONTROL"))
        self.assertEqual(pf.start_plan(info, "DUPLICATION"), (-40., True))
        self.assertEqual(pf.start_plan(info, "BACKUP"), (0., False))

    def test_file_without_layer_mark_moves_as_a_whole(self):
        data = FILE.replace(b";LAYER_CHANGE\n", b"")
        info = pf.analyze(self.write(data))
        self.assertIsNone(info["layer_pos"])
        # Center of the whole file (0 to 140) to 80
        self.assertEqual(pf.start_plan(info, "DUPLICATION"), (10., False))

    def test_too_wide_and_dual_extrusion(self):
        wide = FILE.replace(b"G1 X140 Y100 E1.0", b"G1 X300 Y100 E1.0")
        info = pf.analyze(self.write(wide))
        self.assertIn("too large", pf.check_mode(info, "DUPLICATION"))
        self.assertIsNone(pf.check_mode(info, "BACKUP"))
        dual = FILE + b"T1\nG1 X10 Y10 E1\n"
        info = pf.analyze(self.write(dual))
        self.assertIn("Backup", pf.check_mode(info, "BACKUP"))
        self.assertIn("dual-extrusion", pf.check_mode(info, "MIRROR"))

    def test_make_copy_inserts_offset_before_first_layer(self):
        os.makedirs(os.path.join(self.gcodes, "sub"))
        self.write(FILE, "sub/part.gcode")
        pos = pf.analyze(os.path.join(self.gcodes, "sub/part.gcode"))[
            "layer_pos"]
        pf.CHUNK = 7
        name = pf.make_copy("sub/part.gcode", pos, -40., self.gcodes)
        self.assertEqual(name, pf.COPY_DIR + "/part.gcode")
        with open(os.path.join(self.gcodes, name), "rb") as f:
            copy = f.read()
        line = b"SET_GCODE_OFFSET X=-40.00 ; moved for the print mode\n"
        self.assertEqual(copy, FILE[:pos] + line + FILE[pos:])
        # The next copy replaces it
        self.write(FILE, "other.gcode")
        pf.make_copy("other.gcode", pos, 5., self.gcodes)
        self.assertEqual(os.listdir(os.path.join(self.gcodes, pf.COPY_DIR)),
                         ["other.gcode"])

    def test_print_command(self):
        self.assertEqual(pf.print_command("a b.gcode"),
                         'SDCARD_PRINT_FILE FILENAME="a b.gcode"')
        self.assertEqual(pf.print_command("a.gcode", "MIRROR", -45.),
                         'SDCARD_PRINT_FILE FILENAME="a.gcode" MODE=MIRROR'
                         ' X_OFFSET=-45.00')


if __name__ == "__main__":
    unittest.main()
